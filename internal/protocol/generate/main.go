// Command generate は protocol.schema.json から、バイナリの Go の型と mod の TypeScript を生成する
// (`task protocol:generate`、protocol の go:generate)。go generate が protocol のディレクトリを cwd にして走らせる。
//
// mod の types は plugin の型の契約で 1 ファイルに閉じるので、手書きの PluginState と同じファイルの生成の印の間に書く。
// cc-premise: 2.1.314 mods plugin validate は types の import と export from を拒む
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"slices"
)

const (
	goHeader = "// Code generated by task protocol:generate from protocol/protocol.schema.json. DO NOT EDIT."
	tsHeader = "// @generated by `task protocol:generate` from protocol/protocol.schema.json. DO NOT EDIT."

	beginMark = "// protocol:begin\n" + tsHeader + "\n"
	endMark   = "// protocol:end\n"

	// protocol のディレクトリからの置き場。
	schemaPath      = "protocol.schema.json"
	goPath          = "types.go"
	typesPath       = "../../types/index.d.ts"
	definitionsPath = "../../hooks/protocol.ts"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "generate:", err)
		os.Exit(1)
	}
}

func run() error {
	schema, err := os.ReadFile(schemaPath)
	if err != nil {
		return err
	}
	var doc node
	if err := json.Unmarshal(schema, &doc); err != nil {
		return err
	}
	defs := doc.fields["$defs"]
	if defs == nil {
		return fmt.Errorf("%s に $defs が無い", schemaPath)
	}

	goSrc, err := goTypes(defs)
	if err != nil {
		return err
	}
	types, err := tsTypes(defs)
	if err != nil {
		return err
	}
	definitions, err := tsDefinitions(schema)
	if err != nil {
		return err
	}
	current, err := os.ReadFile(typesPath)
	if err != nil {
		return err
	}
	head, rest, ok := bytes.Cut(current, []byte(beginMark))
	_, tail, ok2 := bytes.Cut(rest, []byte(endMark))
	if !ok || !ok2 {
		return fmt.Errorf("%s に生成の印 (protocol:begin と protocol:end) が無い", typesPath)
	}

	for path, data := range map[string][]byte{
		goPath:          goSrc,
		typesPath:       slices.Concat(head, []byte(beginMark), types, []byte(endMark), tail),
		definitionsPath: definitions,
	} {
		if err := os.WriteFile(path, data, 0o644); err != nil { // #nosec G306 -- repo に commit するソース
			return err
		}
	}
	return nil
}

// node は schema の 1 つの値。object の欄の順を書いた順のまま持つ (生成物の欄を schema と同じ順に並べるため)。
type node struct {
	keys   []string
	fields map[string]*node
	items  []*node
	scalar any
}

func (n *node) UnmarshalJSON(data []byte) error {
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.UseNumber()
	return n.read(dec)
}

func (n *node) read(dec *json.Decoder) error {
	tok, err := dec.Token()
	if err != nil {
		return err
	}
	switch tok {
	case json.Delim('{'):
		n.fields = make(map[string]*node)
		for dec.More() {
			key, err := dec.Token()
			if err != nil {
				return err
			}
			child := &node{}
			if err := child.read(dec); err != nil {
				return err
			}
			n.keys = append(n.keys, key.(string))
			n.fields[key.(string)] = child
		}
		_, err = dec.Token()
		return err
	case json.Delim('['):
		n.items = []*node{}
		for dec.More() {
			child := &node{}
			if err := child.read(dec); err != nil {
				return err
			}
			n.items = append(n.items, child)
		}
		_, err = dec.Token()
		return err
	}
	n.scalar = tok
	return nil
}

func (n *node) str(key string) string {
	if f, ok := n.fields[key]; ok {
		if s, ok := f.scalar.(string); ok {
			return s
		}
	}
	return ""
}

// required は object の required の欄の集合。
func (n *node) required() map[string]bool {
	out := make(map[string]bool)
	if r, ok := n.fields["required"]; ok {
		for _, v := range r.items {
			if s, ok := v.scalar.(string); ok {
				out[s] = true
			}
		}
	}
	return out
}

func refName(ref string) string {
	const prefix = "#/$defs/"
	if len(ref) > len(prefix) && ref[:len(prefix)] == prefix {
		return ref[len(prefix):]
	}
	return ref
}
